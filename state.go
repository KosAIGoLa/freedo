// state.go: the indexer's in-memory view, stats, alerts and snapshot
// persistence. All state access goes through the mutex.
package main

import (
	"encoding/json"
	"math/big"
	"os"
	"sort"
	"strings"
	"sync"
	"time"
)

// Processor is one TapeOut CPU contract deployed by the factory.
// Numeric values are decimal strings so JSON stays exact for big ints.
type Processor struct {
	Address    string         `json:"address"`
	Index      int            `json:"index"`
	Circuits   string         `json:"circuits"`
	Transistor string         `json:"transistor,omitempty"`
	Price      string         `json:"price,omitempty"`
	Minted     string         `json:"minted,omitempty"`
	Cap        string         `json:"cap,omitempty"`
	FirstSeen  time.Time      `json:"first_seen"`
	LastSeen   time.Time      `json:"last_seen"`
	History    []HistoryPoint `json:"history,omitempty"`
}

// HistoryPoint records a processor's circuit count at a sync.
type HistoryPoint struct {
	Time     time.Time `json:"time"`
	Block    uint64    `json:"block"`
	Circuits string    `json:"circuits"`
}

// Alert kinds.
const (
	AlertNewProcessor = "new_processor"
	AlertNewCircuits  = "new_circuits"
)

// Alert is one noteworthy change found by a sync.
type Alert struct {
	Seq     int       `json:"seq"` // sync sequence that generated it
	Time    time.Time `json:"time"`
	Block   uint64    `json:"block"`
	Kind    string    `json:"kind"`
	Address string    `json:"address"`
	Detail  string    `json:"detail"`
}

const (
	maxAlerts  = 200 // alerts kept (newest first)
	maxHistory = 200 // history points kept per processor
)

// Snapshot is the on-disk form of the state.
type Snapshot struct {
	Factory     string      `json:"factory"`
	Block       string      `json:"block"`
	BlockNumber uint64      `json:"block_number"`
	SyncedAt    time.Time   `json:"synced_at"`
	SyncSeq     int         `json:"sync_seq"`
	Syncs       int         `json:"syncs"`
	SyncErrors  int         `json:"sync_errors"`
	LastSyncErr string      `json:"last_sync_error,omitempty"`
	LastSyncMs  int64       `json:"last_sync_ms"`
	Processors  []Processor `json:"processors"`
	Alerts      []Alert     `json:"alerts"`
}

// State holds the indexer's view of the factory.
type State struct {
	mu sync.RWMutex

	Factory      string
	Block        string // requested block tag ("latest" or hex)
	BlockNumber  uint64
	SyncedAt     time.Time
	SyncSeq      int
	Syncs        int
	SyncErrors   int
	LastSyncErr  string
	LastSyncTook time.Duration

	processors map[string]*Processor // key: lowercase address
	alerts     []Alert               // newest first
}

func NewState(factory, block string) *State {
	return &State{
		Factory:    factory,
		Block:      block,
		processors: make(map[string]*Processor),
	}
}

func circuitsBig(p *Processor) *big.Int {
	n, ok := new(big.Int).SetString(p.Circuits, 10)
	if !ok {
		return big.NewInt(0)
	}
	return n
}

// sortProcessors orders by circuits descending, ties by address ascending.
func sortProcessors(ps []*Processor) {
	sort.Slice(ps, func(i, j int) bool {
		a, b := circuitsBig(ps[i]), circuitsBig(ps[j])
		if c := a.Cmp(b); c != 0 {
			return c > 0
		}
		return strings.ToLower(ps[i].Address) < strings.ToLower(ps[j].Address)
	})
}

// Merge folds freshly fetched processors into the state. It returns the
// alerts generated by this sync. Alerts are suppressed on the very first
// sync (bootstrap: there is no previous sync to compare against).
func (s *State) Merge(fetched []*Processor, blockNum uint64, now time.Time) []Alert {
	s.mu.Lock()
	defer s.mu.Unlock()

	bootstrap := len(s.processors) == 0
	s.SyncSeq++
	s.SyncedAt = now
	s.BlockNumber = blockNum

	var generated []Alert
	for _, f := range fetched {
		key := strings.ToLower(f.Address)
		prev, known := s.processors[key]
		if !known {
			f.FirstSeen = now
			f.LastSeen = now
			f.History = []HistoryPoint{{Time: now, Block: blockNum, Circuits: f.Circuits}}
			cp := *f
			s.processors[key] = &cp
			if !bootstrap {
				generated = append(generated, Alert{
					Seq: s.SyncSeq, Time: now, Block: blockNum,
					Kind: AlertNewProcessor, Address: f.Address,
					Detail: "processor deployed (index " + itoa(f.Index) + ")",
				})
			}
			continue
		}
		oldCircuits := circuitsBig(prev)
		newCircuits := circuitsBig(f)
		if newCircuits.Cmp(oldCircuits) > 0 {
			delta := new(big.Int).Sub(newCircuits, oldCircuits)
			if !bootstrap {
				generated = append(generated, Alert{
					Seq: s.SyncSeq, Time: now, Block: blockNum,
					Kind: AlertNewCircuits, Address: f.Address,
					Detail: "circuits " + oldCircuits.String() + " -> " + newCircuits.String() + " (+" + delta.String() + ")",
				})
			}
		}
		prev.Index = f.Index
		prev.Circuits = f.Circuits
		if f.Transistor != "" {
			prev.Transistor = f.Transistor
		}
		if f.Price != "" {
			prev.Price = f.Price
		}
		if f.Minted != "" {
			prev.Minted = f.Minted
		}
		if f.Cap != "" {
			prev.Cap = f.Cap
		}
		prev.LastSeen = now
		// Record a history point when circuits changed, or at most once
		// an hour for unchanged processors (keeps snapshots small).
		lastCircuits := ""
		lastTime := time.Time{}
		if len(prev.History) > 0 {
			lastCircuits = prev.History[len(prev.History)-1].Circuits
			lastTime = prev.History[len(prev.History)-1].Time
		}
		if lastCircuits != f.Circuits || now.Sub(lastTime) >= time.Hour {
			prev.History = append(prev.History, HistoryPoint{Time: now, Block: blockNum, Circuits: f.Circuits})
			if len(prev.History) > maxHistory {
				prev.History = prev.History[len(prev.History)-maxHistory:]
			}
		}
	}
	if len(generated) > 0 {
		// Newest first.
		for i, j := 0, len(generated)-1; i < j; i, j = i+1, j-1 {
			generated[i], generated[j] = generated[j], generated[i]
		}
		s.alerts = append(generated, s.alerts...)
		if len(s.alerts) > maxAlerts {
			s.alerts = s.alerts[:maxAlerts]
		}
	}
	return generated
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}

// TopHolder is one entry of the leaderboard's head.
type TopHolder struct {
	Address  string  `json:"address"`
	Circuits string  `json:"circuits"`
	SharePct float64 `json:"share_pct"`
}

// Stats is the /api/stats response.
type Stats struct {
	Factory        string      `json:"factory"`
	Processors     int         `json:"processors"`
	TotalCircuits  string      `json:"total_circuits"`
	ZeroCircuits   int         `json:"zero_circuit_processors"`
	MedianCircuits string      `json:"median_circuits"`
	Top3SharePct   float64     `json:"top3_share_pct"`
	TopHolders     []TopHolder `json:"top_holders"`
	LastSyncAt     time.Time   `json:"last_sync_at"`
	Block          string      `json:"block"`
	BlockNumber    uint64      `json:"block_number"`
	Syncs          int         `json:"syncs"`
	SyncErrors     int         `json:"sync_errors"`
	LastSyncErr    string      `json:"last_sync_error,omitempty"`
	LastSyncTookMs int64       `json:"last_sync_ms"`
}

// Stats computes the current aggregate view.
func (s *State) Stats() Stats {
	s.mu.RLock()
	defer s.mu.RUnlock()

	list := make([]*Processor, 0, len(s.processors))
	for _, p := range s.processors {
		list = append(list, p)
	}
	sortProcessors(list)

	total := big.NewInt(0)
	zero := 0
	values := make([]*big.Int, 0, len(list))
	for _, p := range list {
		c := circuitsBig(p)
		total.Add(total, c)
		values = append(values, c)
		if c.Sign() == 0 {
			zero++
		}
	}
	// Median over circuit counts (ascending).
	asc := make([]*big.Int, len(values))
	copy(asc, values)
	sort.Slice(asc, func(i, j int) bool { return asc[i].Cmp(asc[j]) < 0 })
	median := big.NewInt(0)
	if len(asc) > 0 {
		mid := len(asc) / 2
		if len(asc)%2 == 1 {
			median = asc[mid]
		} else {
			median = new(big.Int).Add(asc[mid-1], asc[mid])
			median.Div(median, big.NewInt(2))
		}
	}
	top := 3
	if len(list) < top {
		top = len(list)
	}
	topSum := big.NewInt(0)
	holders := make([]TopHolder, 0, top)
	for i := 0; i < top; i++ {
		c := circuitsBig(list[i])
		topSum.Add(topSum, c)
		share := 0.0
		if total.Sign() > 0 {
			f, _ := new(big.Float).Quo(new(big.Float).SetInt(c), new(big.Float).SetInt(total)).Float64()
			share = f * 100
		}
		holders = append(holders, TopHolder{Address: list[i].Address, Circuits: c.String(), SharePct: share})
	}
	top3Share := 0.0
	if total.Sign() > 0 {
		f, _ := new(big.Float).Quo(new(big.Float).SetInt(topSum), new(big.Float).SetInt(total)).Float64()
		top3Share = f * 100
	}
	return Stats{
		Factory: s.Factory, Processors: len(list),
		TotalCircuits: total.String(), ZeroCircuits: zero,
		MedianCircuits: median.String(), Top3SharePct: top3Share,
		TopHolders: holders, LastSyncAt: s.SyncedAt, Block: s.Block,
		BlockNumber: s.BlockNumber, Syncs: s.Syncs, SyncErrors: s.SyncErrors,
		LastSyncErr: s.LastSyncErr, LastSyncTookMs: s.LastSyncTook.Milliseconds(),
	}
}

// Leaderboard returns all processors sorted by circuits descending.
func (s *State) Leaderboard() []*Processor {
	s.mu.RLock()
	defer s.mu.RUnlock()
	list := make([]*Processor, 0, len(s.processors))
	for _, p := range s.processors {
		cp := *p
		list = append(list, &cp)
	}
	sortProcessors(list)
	return list
}

// GetProcessor returns a copy of one processor by address
// (case-insensitive), or false when unknown.
func (s *State) GetProcessor(addr string) (*Processor, bool) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	p, ok := s.processors[strings.ToLower(addr)]
	if !ok {
		return nil, false
	}
	cp := *p
	return &cp, true
}

// Alerts returns the newest alerts, optionally only those at or after
// since (zero time = all), capped at limit (0 = 50).
func (s *State) Alerts(since time.Time, limit int) []Alert {
	if limit <= 0 {
		limit = 50
	}
	s.mu.RLock()
	defer s.mu.RUnlock()
	out := make([]Alert, 0, limit)
	for _, a := range s.alerts {
		if !since.IsZero() && a.Time.Before(since) {
			continue
		}
		out = append(out, a)
		if len(out) >= limit {
			break
		}
	}
	return out
}

// AlertsForSync returns alerts generated by the latest sync.
func (s *State) AlertsForSync() []Alert {
	s.mu.RLock()
	defer s.mu.RUnlock()
	out := make([]Alert, 0)
	for _, a := range s.alerts {
		if a.Seq == s.SyncSeq {
			out = append(out, a)
		}
	}
	return out
}

// Seq returns the current sync sequence number.
func (s *State) Seq() int {
	s.mu.RLock()
	defer s.mu.RUnlock()
	return s.SyncSeq
}

// Snapshot serializes the state for disk.
func (s *State) Snapshot() Snapshot {
	s.mu.RLock()
	defer s.mu.RUnlock()
	procs := make([]Processor, 0, len(s.processors))
	for _, p := range s.processors {
		procs = append(procs, *p)
	}
	sort.Slice(procs, func(i, j int) bool { return procs[i].Index < procs[j].Index })
	alerts := make([]Alert, len(s.alerts))
	copy(alerts, s.alerts)
	return Snapshot{
		Factory: s.Factory, Block: s.Block, BlockNumber: s.BlockNumber,
		SyncedAt: s.SyncedAt, SyncSeq: s.SyncSeq, Syncs: s.Syncs,
		SyncErrors: s.SyncErrors, LastSyncErr: s.LastSyncErr,
		LastSyncMs: s.LastSyncTook.Milliseconds(),
		Processors: procs, Alerts: alerts,
	}
}

// Restore loads a snapshot into the state.
func (s *State) Restore(snap Snapshot) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.Factory = snap.Factory
	s.Block = snap.Block
	s.BlockNumber = snap.BlockNumber
	s.SyncedAt = snap.SyncedAt
	s.SyncSeq = snap.SyncSeq
	s.Syncs = snap.Syncs
	s.SyncErrors = snap.SyncErrors
	s.LastSyncErr = snap.LastSyncErr
	s.LastSyncTook = time.Duration(snap.LastSyncMs) * time.Millisecond
	s.processors = make(map[string]*Processor, len(snap.Processors))
	for i := range snap.Processors {
		p := snap.Processors[i]
		s.processors[strings.ToLower(p.Address)] = &p
	}
	s.alerts = append([]Alert(nil), snap.Alerts...)
}

// Save writes the snapshot atomically (temp file + rename).
func (s *State) Save(path string) error {
	data, err := json.MarshalIndent(s.Snapshot(), "", "  ")
	if err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// Load reads a snapshot from disk. os.ErrNotExist means "no snapshot yet".
func (s *State) Load(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var snap Snapshot
	if err := json.Unmarshal(data, &snap); err != nil {
		return err
	}
	s.Restore(snap)
	return nil
}
